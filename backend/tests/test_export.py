"""Downloading an assistant answer as Word (.docx) or Markdown."""

import io
from datetime import datetime

import pytest
from docx import Document as DocxDocument

from apps.chat.models import Conversation, Message
from services.export import export_filename, to_docx

pytestmark = pytest.mark.django_db

ANSWER = """# Refund Policy Summary

Customers can get a **full refund** within *30 days* [1].

## Eligibility

- Unused items only [1]
  - Original packaging
- Receipt required

1. Contact support
2. Ship the item [2]

| Plan | Refund window |
|------|---------------|
| Basic | 14 days |
| Pro | 30 days |

> Refunds take 5-7 business days.
"""

CITATIONS = [
    {"index": 1, "document_id": 1, "chunk_id": 1, "title": "Policy", "file_type": "pdf", "page": 3},
    {
        "index": 2,
        "document_id": 2,
        "chunk_id": 9,
        "title": "Prices",
        "file_type": "xlsx",
        "page": 2,
    },
]


@pytest.fixture
def answer(workspace, user):
    conv = Conversation.objects.create(workspace=workspace, user=user, title="refunds?")
    Message.objects.create(conversation=conv, role="user", content="Create a refund summary")
    return Message.objects.create(
        conversation=conv, role="assistant", content=ANSWER, citations=CITATIONS
    )


def url(message_id: int, fmt: str = "docx") -> str:
    return f"/api/messages/{message_id}/export/{fmt}/"


def read_docx(content: bytes):
    return DocxDocument(io.BytesIO(content))


def test_docx_export_keeps_structure_and_lists_sources(auth_client, answer):
    res = auth_client.get(url(answer.id))
    assert res.status_code == 200
    assert res["Content-Type"].startswith("application/vnd.openxmlformats")
    # The answer's own "# Title" names the file and isn't repeated in the body.
    assert 'filename="Refund Policy Summary.docx"' in res["Content-Disposition"]

    doc = read_docx(res.content)
    paras = [(p.style.name, p.text) for p in doc.paragraphs]
    assert paras[0] == ("Title", "Refund Policy Summary")
    assert sum(text == "Refund Policy Summary" for _, text in paras) == 1
    assert ("Heading 2", "Eligibility") in paras
    assert ("List Bullet", "Unused items only [1]") in paras
    assert ("List Bullet 2", "Original packaging") in paras
    assert ("List Paragraph", "2. Ship the item [2]") in paras
    assert ("Quote", "Refunds take 5-7 business days.") in paras
    assert ("Heading 1", "Sources") in paras
    assert ("List Bullet", "[1] Policy — page 3") in paras
    assert ("List Bullet", "[2] Prices — sheet 2") in paras

    intro = next(p for p in doc.paragraphs if p.text.startswith("Customers"))
    assert intro.text == "Customers can get a full refund within 30 days [1]."
    assert [r.text for r in intro.runs if r.bold] == ["full refund"]
    assert [r.text for r in intro.runs if r.italic] == ["30 days"]

    [table] = doc.tables
    assert [[c.text for c in row.cells] for row in table.rows] == [
        ["Plan", "Refund window"],
        ["Basic", "14 days"],
        ["Pro", "30 days"],
    ]


def test_markdown_export(auth_client, answer):
    res = auth_client.get(url(answer.id, "md"))
    assert res.status_code == 200
    assert res["Content-Type"].startswith("text/markdown")
    text = res.content.decode()
    assert text.startswith("# Refund Policy Summary\n\n_Generated by DocuChat")
    assert "## Eligibility" in text
    assert text.rstrip().endswith("- [1] Policy — page 3\n- [2] Prices — sheet 2")


def test_answer_without_title_uses_conversation_title(auth_client, answer):
    answer.content = "Short answer [1]."
    answer.save()
    res = auth_client.get(url(answer.id))
    assert 'filename="refunds.docx"' in res["Content-Disposition"]
    assert read_docx(res.content).paragraphs[0].text == "refunds?"


def test_only_own_assistant_messages_can_be_exported(auth_client, api_client, other_user, answer):
    from rest_framework.test import APIClient

    bob = APIClient()
    bob.force_authenticate(other_user)
    assert bob.get(url(answer.id)).status_code == 404
    assert api_client.get(url(answer.id)).status_code == 401
    question = answer.conversation.messages.get(role="user")
    assert auth_client.get(url(question.id)).status_code == 404  # questions aren't exportable
    assert auth_client.get(url(answer.id, "pdf")).status_code == 404


def test_unrecognised_markdown_is_kept_as_text():
    content = "Odd **unclosed bold and a_snake_case name\n```\ncode line\n```"
    doc = read_docx(to_docx("T", content, [], datetime(2026, 1, 1)))
    texts = [p.text for p in doc.paragraphs]
    assert "Odd **unclosed bold and a_snake_case name" in texts
    assert "code line" in texts


def test_export_filename_is_safe():
    assert export_filename('Q3 "report": a/b\\c?', "docx") == "Q3 report abc.docx"
    assert export_filename("   ", "md") == "DocuChat answer.md"
    assert len(export_filename("x" * 300, "docx")) == 85
