"""Turn an assistant answer (Markdown) into a downloadable Word or Markdown file.

The model already answers in a small, predictable subset of Markdown (headings,
lists, bold/italic, tables, quotes, code), so a line-based converter covers it
without adding a Markdown library. It isn't a full CommonMark parser; anything
it doesn't recognise is kept as plain text, so no content is ever lost.
"""

import io
import re
from collections.abc import Sequence
from datetime import datetime

from docx import Document as DocxDocument
from docx.document import Document as DocxDocumentType
from docx.shared import Pt, RGBColor
from docx.text.paragraph import Paragraph

DOCX_CONTENT_TYPE = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
MARKDOWN_CONTENT_TYPE = "text/markdown; charset=utf-8"

_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_BULLET_RE = re.compile(r"^(\s*)[-*+]\s+(.*)$")
_NUMBERED_RE = re.compile(r"^(\s*)(\d+)[.)]\s+(.*)$")
_TABLE_SEP_RE = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
_HR_RE = re.compile(r"^\s*([-*_])(\s*\1){2,}\s*$")
# Inline: **bold**, __bold__, *italic*, _italic_, `code`, [text](url)
_INLINE_RE = re.compile(
    r"\*\*(?P<b1>.+?)\*\*|__(?P<b2>.+?)__|`(?P<code>[^`]+)`"
    r"|\[(?P<ltext>[^\]]+)\]\((?P<lurl>[^)\s]+)\)"
    r"|(?<![\w*])\*(?P<i1>[^*\s][^*]*?)\*(?!\w)|(?<![\w_])_(?P<i2>[^_\s][^_]*?)_(?!\w)"
)


def location_label(file_type: str | None, page: int) -> str:
    if file_type == "csv":
        return ""
    return f"{'sheet' if file_type == 'xlsx' else 'page'} {page}"


def sources_lines(citations: Sequence[dict]) -> list[str]:
    """'[1] Policy — page 3' for each citation, in the order the answer cites them."""
    lines = []
    for c in citations:
        where = location_label(c.get("file_type"), c.get("page", 0))
        lines.append(f"[{c['index']}] {c['title']}" + (f" — {where}" if where else ""))
    return lines


# ---------- Markdown ----------


def to_markdown(title: str, content: str, citations: Sequence[dict], created: datetime) -> bytes:
    parts = [f"# {title}", f"_Generated by DocuChat from your documents · {created:%d %b %Y}_"]
    parts.append(content.strip())
    if citations:
        parts.append("## Sources\n\n" + "\n".join(f"- {line}" for line in sources_lines(citations)))
    return ("\n\n".join(parts) + "\n").encode()


# ---------- Word ----------


def _add_inline(paragraph: Paragraph, text: str, bold: bool = False) -> None:
    """Append `text` to `paragraph`, turning inline Markdown into Word formatting."""
    pos = 0
    for m in _INLINE_RE.finditer(text):
        if m.start() > pos:
            paragraph.add_run(text[pos : m.start()]).bold = bold or None
        if m["b1"] or m["b2"]:
            _add_inline(paragraph, m["b1"] or m["b2"], bold=True)
        elif m["code"]:
            run = paragraph.add_run(m["code"])
            run.font.name = "Consolas"
            run.bold = bold or None
        elif m["ltext"]:
            paragraph.add_run(f"{m['ltext']} ({m['lurl']})").bold = bold or None
        else:
            run = paragraph.add_run(m["i1"] or m["i2"])
            run.italic = True
            run.bold = bold or None
        pos = m.end()
    if pos < len(text):
        paragraph.add_run(text[pos:]).bold = bold or None


def _split_row(line: str) -> list[str]:
    line = line.strip()
    line = line.removeprefix("|").removesuffix("|")
    return [cell.strip() for cell in line.split("|")]


def _add_table(doc: DocxDocumentType, rows: list[list[str]]) -> None:
    width = max(len(r) for r in rows)
    table = doc.add_table(rows=len(rows), cols=width)
    table.style = "Table Grid"
    for r, cells in enumerate(rows):
        for c in range(width):
            paragraph = table.cell(r, c).paragraphs[0]
            _add_inline(paragraph, cells[c] if c < len(cells) else "", bold=r == 0)


def _render_markdown(doc: DocxDocumentType, markdown: str) -> None:
    lines = markdown.replace("\r\n", "\n").split("\n")
    paragraph_buf: list[str] = []

    def flush() -> None:
        if paragraph_buf:
            _add_inline(doc.add_paragraph(), " ".join(s.strip() for s in paragraph_buf))
            paragraph_buf.clear()

    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if stripped.startswith("```"):  # fenced code block
            flush()
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                run = doc.add_paragraph().add_run(lines[i])
                run.font.name = "Consolas"
                run.font.size = Pt(9)
                i += 1
            i += 1
            continue

        if stripped.startswith("|") and i + 1 < len(lines) and _TABLE_SEP_RE.match(lines[i + 1]):
            flush()
            rows = [_split_row(line)]
            i += 2
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(_split_row(lines[i]))
                i += 1
            _add_table(doc, rows)
            continue

        if not stripped:
            flush()
        elif m := _HEADING_RE.match(stripped):
            flush()
            doc.add_heading(m[2], level=min(len(m[1]), 4))
        elif _HR_RE.match(stripped):
            flush()
        elif m := _BULLET_RE.match(line):
            flush()
            nested = len(m[1].expandtabs(4)) >= 2
            _add_inline(doc.add_paragraph(style="List Bullet 2" if nested else "List Bullet"), m[2])
        elif m := _NUMBERED_RE.match(line):
            flush()
            # Word's "List Number" style shares one counter across the whole file,
            # so a second list would continue from the first. Writing the model's
            # own number keeps every list numbered exactly as in the answer.
            p = doc.add_paragraph(style="List Paragraph")
            if len(m[1].expandtabs(4)) >= 2:
                p.paragraph_format.left_indent = Pt(36)
            p.add_run(f"{m[2]}. ")
            _add_inline(p, m[3])
        elif stripped.startswith(">"):
            flush()
            _add_inline(doc.add_paragraph(style="Quote"), stripped.lstrip("> ").strip())
        else:
            paragraph_buf.append(line)
        i += 1
    flush()


def to_docx(title: str, content: str, citations: Sequence[dict], created: datetime) -> bytes:
    doc = DocxDocument()
    doc.add_heading(title, level=0)
    note = doc.add_paragraph().add_run(
        f"Generated by DocuChat from your documents · {created:%d %b %Y}"
    )
    note.italic = True
    note.font.color.rgb = RGBColor(0x6B, 0x65, 0x85)

    _render_markdown(doc, content)

    if citations:
        doc.add_heading("Sources", level=1)
        for line in sources_lines(citations):
            doc.add_paragraph(line, style="List Bullet")

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def export_filename(title: str, extension: str) -> str:
    """A safe, readable file name: 'Refund policy summary.docx'."""
    name = re.sub(r"[^\w\s.-]", "", title, flags=re.UNICODE)
    name = re.sub(r"\s+", " ", name).strip(" .")[:80].strip()
    return f"{name or 'DocuChat answer'}.{extension}"
